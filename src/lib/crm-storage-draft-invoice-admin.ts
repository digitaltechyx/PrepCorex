/**
 * Admin/cron helper: write monthly storage drafts to CRM `external_invoices`
 * using Firebase Admin (server routes).
 */

import { format } from "date-fns";
import type { Firestore } from "firebase-admin/firestore";
import {
  CRM_STORAGE_DRAFT_BILLING_SOURCE,
  crmStorageDraftConsolidationKey,
  type CrmStorageDraftLine,
} from "@/lib/crm-storage-draft-invoice";

function money(n: unknown): number {
  const v = Number(n);
  return Number.isFinite(v) ? Math.round(v * 100) / 100 : 0;
}

function newLineId() {
  return `line_${Date.now()}_${Math.random().toString(36).slice(2, 9)}`;
}

export async function createCrmStorageDraftInvoiceAdmin(input: {
  db: Firestore;
  clientUserId: string;
  clientName?: string | null;
  clientEmail?: string | null;
  clientPhone?: string | null;
  invoiceMonth: string;
  lines: CrmStorageDraftLine[];
  palletCycleIds?: string[];
  adminUid?: string | null;
  isTest?: boolean;
  /** When true, always create a new draft (admin test). */
  forceNew?: boolean;
}): Promise<{ externalInvoiceId: string; created: boolean; invoiceNumber: string }> {
  const clientUserId = String(input.clientUserId || "").trim();
  if (!clientUserId) throw new Error("Missing client user id");
  const invoiceMonth = String(input.invoiceMonth || "").trim();

  const lines = (input.lines || [])
    .map((line) => {
      const description = String(line.description || "").trim();
      const quantity = Number(line.quantity) || 0;
      const unitPrice = money(line.unitPrice);
      if (!description || quantity <= 0) return null;
      return {
        id: line.id || newLineId(),
        description,
        quantity,
        unitPrice,
        amount: money(line.amount ?? quantity * unitPrice),
        sourceKey:
          line.sourceKey ||
          `storage:${line.palletCycleId || description}:${quantity}:${unitPrice}`,
      };
    })
    .filter(Boolean) as Array<{
    id: string;
    description: string;
    quantity: number;
    unitPrice: number;
    amount: number;
    sourceKey: string;
  }>;

  if (lines.length === 0) throw new Error("No storage lines to draft");

  const consolidationKey = crmStorageDraftConsolidationKey(clientUserId, invoiceMonth);

  if (!input.forceNew) {
    const existingSnap = await input.db
      .collection("external_invoices")
      .where("consolidationKey", "==", consolidationKey)
      .where("status", "==", "draft")
      .limit(1)
      .get();
    if (!existingSnap.empty) {
      const existing = existingSnap.docs[0]!;
      return {
        externalInvoiceId: existing.id,
        created: false,
        invoiceNumber: String(existing.data()?.invoiceNumber || ""),
      };
    }
  }

  const today = new Date();
  const invoiceDate = format(today, "yyyy-MM-dd");
  const due = new Date(today);
  due.setDate(due.getDate() + 2);
  const dueDate = format(due, "yyyy-MM-dd");
  const subtotal = money(lines.reduce((sum, l) => sum + l.amount, 0));
  const invoiceNumber = input.forceNew
    ? `DRAFT-STOR-${Date.now().toString().slice(-8)}`
    : `DRAFT-STOR-${invoiceMonth.replace("-", "")}-${Date.now().toString().slice(-4)}`;

  const ref = await input.db.collection("external_invoices").add({
    status: "draft",
    invoiceNumber,
    invoiceDate,
    dueDate,
    companyName: "Prep Services FBA",
    clientName: input.clientName || "Client",
    clientEmail: input.clientEmail || "",
    clientPhone: input.clientPhone || "",
    clientAddress: "",
    items: lines,
    shippingLabelItems: [],
    subtotal,
    salesTax: 0,
    shippingCost: 0,
    total: subtotal,
    amountPaid: 0,
    outstandingBalance: subtotal,
    payments: [],
    billingSource: CRM_STORAGE_DRAFT_BILLING_SOURCE,
    consolidationKey: input.forceNew
      ? `${consolidationKey}-test-${Date.now().toString().slice(-6)}`
      : consolidationKey,
    invoiceMonth,
    type: "storage",
    prepcorexClientUserId: clientUserId,
    palletCycleIds: [...new Set((input.palletCycleIds || []).filter(Boolean))],
    showInPrepcorex: false,
    autoGenerated: true,
    autoGeneratedAt: new Date(),
    ...(input.isTest || input.forceNew ? { isTest: true } : {}),
    createdAt: new Date(),
    updatedAt: new Date(),
    lastPrepcorexAppendBy: input.adminUid || null,
  });

  return { externalInvoiceId: ref.id, created: true, invoiceNumber };
}
