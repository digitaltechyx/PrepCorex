/**
 * Monthly pallet storage → CRM `external_invoices` draft (Storage draft tab).
 * PrepCorex client invoice is created only when admin sends / marks as sent + syncs.
 */

import {
  addDoc,
  collection,
  getDocs,
  limit,
  query,
  serverTimestamp,
  where,
} from "firebase/firestore";
import { format } from "date-fns";
import { db } from "@/lib/firebase";

export const CRM_STORAGE_DRAFT_BILLING_SOURCE = "prepcorex_storage_monthly";

export function crmStorageDraftConsolidationKey(
  clientUserId: string,
  invoiceMonth: string
): string {
  return `${String(clientUserId || "").trim()}_storage_${String(invoiceMonth || "").trim()}`;
}

export function isCrmStorageDraftBillingSource(value?: string | null): boolean {
  return String(value || "").trim() === CRM_STORAGE_DRAFT_BILLING_SOURCE;
}

export type CrmStorageDraftLine = {
  id?: string;
  description: string;
  quantity: number;
  unitPrice: number;
  amount?: number;
  sourceKey?: string;
  palletCycleId?: string;
};

function money(n: unknown): number {
  const v = Number(n);
  return Number.isFinite(v) ? Math.round(v * 100) / 100 : 0;
}

function newLineId() {
  if (typeof crypto !== "undefined" && typeof crypto.randomUUID === "function") {
    return crypto.randomUUID();
  }
  return `line_${Date.now()}_${Math.random().toString(36).slice(2, 9)}`;
}

/**
 * Create (or skip if month draft already exists) a CRM storage draft for one client.
 * Dedupes by consolidationKey + status=draft.
 */
export async function createCrmStorageDraftInvoice(input: {
  clientUserId: string;
  clientName?: string | null;
  clientEmail?: string | null;
  clientPhone?: string | null;
  invoiceMonth: string; // YYYY-MM
  lines: CrmStorageDraftLine[];
  palletCycleIds?: string[];
  adminUid?: string | null;
  isTest?: boolean;
}): Promise<{ externalInvoiceId: string; created: boolean; invoiceNumber: string }> {
  const clientUserId = String(input.clientUserId || "").trim();
  if (!clientUserId) throw new Error("Missing client user id");
  const invoiceMonth = String(input.invoiceMonth || "").trim();
  if (!/^\d{4}-\d{2}$/.test(invoiceMonth) && !invoiceMonth.includes("-test-")) {
    throw new Error("Invalid invoice month");
  }

  const lines = (input.lines || [])
    .map((line) => {
      const description = String(line.description || "").trim();
      const quantity = Number(line.quantity) || 0;
      const unitPrice = money(line.unitPrice);
      if (!description || quantity <= 0) return null;
      return {
        id: line.id || newLineId(),
        description,
        quantity,
        unitPrice,
        amount: money(line.amount ?? quantity * unitPrice),
        sourceKey:
          line.sourceKey ||
          `storage:${line.palletCycleId || description}:${quantity}:${unitPrice}`,
      };
    })
    .filter(Boolean) as Array<{
    id: string;
    description: string;
    quantity: number;
    unitPrice: number;
    amount: number;
    sourceKey: string;
  }>;

  if (lines.length === 0) throw new Error("No storage lines to draft");

  const consolidationKey = crmStorageDraftConsolidationKey(clientUserId, invoiceMonth);

  // Skip if an open storage draft already exists for this client + month.
  const existingSnap = await getDocs(
    query(
      collection(db, "external_invoices"),
      where("consolidationKey", "==", consolidationKey),
      where("status", "==", "draft"),
      limit(1)
    )
  );
  if (!existingSnap.empty) {
    const existing = existingSnap.docs[0]!;
    return {
      externalInvoiceId: existing.id,
      created: false,
      invoiceNumber: String(existing.data()?.invoiceNumber || ""),
    };
  }

  const today = new Date();
  const invoiceDate = format(today, "yyyy-MM-dd");
  const due = new Date(today);
  due.setDate(due.getDate() + 2);
  const dueDate = format(due, "yyyy-MM-dd");
  const subtotal = money(lines.reduce((sum, l) => sum + l.amount, 0));
  const invoiceNumber = `DRAFT-STOR-${Date.now().toString().slice(-8)}`;

  const docRef = await addDoc(collection(db, "external_invoices"), {
    status: "draft",
    invoiceNumber,
    invoiceDate,
    dueDate,
    companyName: "Prep Services FBA",
    clientName: input.clientName || "Client",
    clientEmail: input.clientEmail || "",
    clientPhone: input.clientPhone || "",
    clientAddress: "",
    items: lines,
    shippingLabelItems: [],
    subtotal,
    salesTax: 0,
    shippingCost: 0,
    total: subtotal,
    amountPaid: 0,
    outstandingBalance: subtotal,
    payments: [],
    billingSource: CRM_STORAGE_DRAFT_BILLING_SOURCE,
    consolidationKey,
    invoiceMonth,
    type: "storage",
    prepcorexClientUserId: clientUserId,
    palletCycleIds: [...new Set((input.palletCycleIds || []).filter(Boolean))],
    showInPrepcorex: false,
    autoGenerated: true,
    autoGeneratedAt: serverTimestamp(),
    ...(input.isTest ? { isTest: true } : {}),
    createdAt: serverTimestamp(),
    updatedAt: serverTimestamp(),
    lastPrepcorexAppendBy: input.adminUid || null,
  });

  return { externalInvoiceId: docRef.id, created: true, invoiceNumber };
}
