/**
 * Mirror PrepCorex client invoices into top-level `prepcorex_invoice_sync`
 * for CRM Invoice Sync (fill existing CRM invoice template).
 *
 * Doc id: `${userId}_${invoiceId}` (idempotent).
 */

function asString(value) {
  if (value == null) return "";
  return String(value).trim();
}

function asNumber(value) {
  const n = Number(value);
  return Number.isFinite(n) ? n : 0;
}

function timestampToIso(value) {
  if (!value) return null;
  if (typeof value === "string") return value;
  if (typeof value.toDate === "function") {
    try {
      return value.toDate().toISOString();
    } catch (_) {
      return null;
    }
  }
  if (typeof value.seconds === "number") {
    return new Date(value.seconds * 1000).toISOString();
  }
  return null;
}

function mapItems(items) {
  if (!Array.isArray(items)) return [];
  return items.map((item) => ({
    quantity: asNumber(item.quantity),
    productName: asString(item.productName),
    packaging: asString(item.packaging),
    shipTo: asString(item.shipTo),
    shipDate: asString(item.shipDate) || null,
    unitPrice: asNumber(item.unitPrice),
    amount: asNumber(item.amount),
    shipmentId: asString(item.shipmentId) || null,
  }));
}

function mapAdditionalCharges(charges) {
  if (!Array.isArray(charges)) return [];
  return charges.map((c) => ({
    id: asString(c.id) || null,
    name: asString(c.name),
    amount: asNumber(c.amount),
  }));
}

/**
 * @param {FirebaseFirestore.Firestore} db
 * @param {string} userId
 * @param {string} invoiceId
 * @param {Record<string, unknown>} invoice
 * @param {{ mergeCopied?: boolean }} [opts]
 */
async function upsertPrepcorexInvoiceSync(db, userId, invoiceId, invoice, opts = {}) {
  const mergeCopied = opts.mergeCopied !== false;
  const docId = `${userId}_${invoiceId}`;
  const ref = db.collection("prepcorex_invoice_sync").doc(docId);
  const existing = mergeCopied ? await ref.get() : null;
  const prev = existing && existing.exists ? existing.data() || {} : {};

  const items = mapItems(invoice.items);
  const adminAdditionalCharges = mapAdditionalCharges(invoice.adminAdditionalCharges);
  const payload = {
    sourceUserId: userId,
    sourceInvoiceId: invoiceId,
    invoiceNumber: asString(invoice.invoiceNumber) || invoiceId,
    invoiceDate: asString(invoice.date) || null,
    dueDate: asString(invoice.dueDate) || null,
    clientName: asString(invoice.soldTo && invoice.soldTo.name),
    clientEmail: asString(invoice.soldTo && invoice.soldTo.email),
    clientPhone: asString(invoice.soldTo && invoice.soldTo.phone) || null,
    clientAddress: asString(invoice.soldTo && invoice.soldTo.address) || null,
    type: asString(invoice.type) || null,
    status: asString(invoice.status) || "pending",
    subtotal: asNumber(invoice.subtotal),
    grandTotal: asNumber(
      invoice.grandTotal != null ? invoice.grandTotal : invoice.grossTotal
    ),
    discountType: asString(invoice.discountType) || null,
    discountValue: invoice.discountValue != null ? asNumber(invoice.discountValue) : null,
    discountAmount: invoice.discountAmount != null ? asNumber(invoice.discountAmount) : null,
    lateFeeAmount: invoice.lateFeeAmount != null ? asNumber(invoice.lateFeeAmount) : null,
    itemCount: items.length,
    items,
    adminAdditionalCharges,
    additionalServices: invoice.additionalServices || null,
    autoGenerated: invoice.autoGenerated === true,
    sourceCreatedAt: invoice.createdAt || null,
    sourceCreatedAtIso: timestampToIso(invoice.createdAt),
    syncedAt: new Date(),
    // Preserve copy stamps across re-syncs
    copiedAt: prev.copiedAt || null,
    copiedByUid: prev.copiedByUid || null,
    copiedByEmail: prev.copiedByEmail || null,
    copyCount: typeof prev.copyCount === "number" ? prev.copyCount : 0,
  };

  await ref.set(payload, { merge: true });
  return docId;
}

module.exports = {
  upsertPrepcorexInvoiceSync,
};
